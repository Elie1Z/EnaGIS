#!/usr/bin/env node
/* Phase 4R: run the registered evaluation and freeze the siting model.
 * Usage: node live/tools/train-siting.cjs data/rwanda/siting_cells.csv
 * Writes: live/js/siting-model.js (frozen model + evaluation shown in the app)
 *         docs/audits/phase4r-evaluation.json (full results, protocol and input hashes)
 * Deterministic: same table -> same output.
 */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const ROOT = path.join(__dirname, "..", "..");
const S = require(path.join(ROOT, "live/js/siting.js"));

const file = process.argv[2] || path.join(ROOT, "data/rwanda/siting_cells.csv");
const text = fs.readFileSync(file, "utf8");
const sha = (buf) => crypto.createHash("sha256").update(buf).digest("hex");

function parseCSV(t) {
  const lines = t.split(/\r?\n/).filter(Boolean), head = lines[0].split(",");
  const num = new Set(["lon", "lat", "nb", "nbN", "n200", "n600", "amax", "maj_km", "min_km", "d_maj", "d_pow", "d_set", "urb", "y", "y_any"]);
  return lines.slice(1).map(line => {
    const cells = []; let cur = "", q = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') q = false; else cur += ch; }
      else if (ch === '"') q = true; else if (ch === ",") { cells.push(cur); cur = ""; } else cur += ch;
    }
    cells.push(cur);
    const r = {}; head.forEach((h, k) => { r[h] = num.has(h) ? +cells[k] : cells[k]; });
    return r;
  });
}

const rows = parseCSV(text);
const protocolPath = path.join(ROOT, "docs/spec/phase4r-protocol.md");
const t0 = Date.now();
// Protocol v1.1: the v1 label (processing or storage only) is evaluated first; if it fails the feasibility gate,
// the primary label becomes y_any (documented aggregation or processing points: + markets and cooperatives).
const v1 = S.evaluate(rows, {label: "y"});
const label = v1.verdict === "FEASIBILITY" ? "y_any" : "y";
const evaluation = label === "y" ? v1 : S.evaluate(rows, {label});
const sensitivity = label === "y" ? S.evaluate(rows, {label: "y_any", draws: 500}) : null;
const model = S.train(rows, {label});
const out = {
  schema: "enagis-phase4r-evaluation-v1", generated_at: new Date().toISOString(), seconds: (Date.now() - t0) / 1000,
  protocol: {file: "docs/spec/phase4r-protocol.md", sha256: sha(fs.readFileSync(protocolPath))},
  code: {file: "live/js/siting.js", sha256: sha(fs.readFileSync(path.join(ROOT, "live/js/siting.js")))},
  input: {file: path.relative(ROOT, file), sha256: sha(Buffer.from(text)), rows: rows.length},
  protocol_version: "v1.1", label, v1_processing_or_storage: {verdict: v1.verdict, positive_cells: v1.positive_cells, positive_districts: v1.positive_districts,
    gate: v1.gate, arms: v1.gate ? v1.arms : null},
  verdict: evaluation.verdict, evaluation,
  sensitivity_any_aggregation_point: sensitivity && {verdict_descriptive: sensitivity.verdict, arms: sensitivity.arms, margin: sensitivity.margin},
  model
};
fs.mkdirSync(path.join(ROOT, "docs/audits"), {recursive: true});
fs.writeFileSync(path.join(ROOT, "docs/audits/phase4r-evaluation.json"), JSON.stringify(out, null, 1));
const app = {version: "phase4r-v1.1", verdict: evaluation.verdict, label, v1_verdict: v1.verdict, v1_positive_cells: v1.positive_cells, model,
  evaluation: {districts: evaluation.districts, positive_cells: evaluation.positive_cells, positive_districts: evaluation.positive_districts,
    arms: evaluation.arms, best_baseline: evaluation.best_baseline, margin: evaluation.margin, roof_gain: evaluation.roof_gain}};
fs.writeFileSync(path.join(ROOT, "live/js/siting-model.js"),
  `/* EnaGIS siting model, frozen (Phase 4R). Generated by live/tools/train-siting.cjs from ${path.relative(ROOT, file)}\n` +
  ` * (sha256 ${out.input.sha256.slice(0, 16)}…) under docs/spec/phase4r-protocol.md. Do not edit by hand. */\n` +
  `window.EnaSitingModel = ${JSON.stringify(app)};\n`);
const pct = v => (v * 100).toFixed(1) + "%";
console.log(`cells ${rows.length}, districts ${evaluation.districts}, positive cells ${evaluation.positive_cells} in ${evaluation.positive_districts} districts`);
evaluation.arms.forEach(a => console.log(`${a.arm.padEnd(16)} recall@10 ${pct(a.recall[0].point)} [${a.recall[0].ci.map(pct).join(", ")}]  recall@20 ${pct(a.recall[1].point)}  AUC ${a.auc === null ? "-" : a.auc.toFixed(3)}`));
console.log(`margin vs best baseline (${evaluation.best_baseline[0]}): ${pct(evaluation.margin[0].point)} [${evaluation.margin[0].ci.map(pct).join(", ")}]  -> ${evaluation.verdict}`);
