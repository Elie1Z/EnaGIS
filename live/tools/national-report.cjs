#!/usr/bin/env node
/* Writes docs/rwanda-national-screening.md from the harvest's district summaries
 * (data/rwanda/district_summaries.json: every district analysed in the browser with the shipped engine).
 * Usage: node live/tools/national-report.cjs [summaries.json]
 */
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..", "..");
const file = process.argv[2] || path.join(ROOT, "data/rwanda/district_summaries.json");
const S = JSON.parse(fs.readFileSync(file, "utf8"));
const prod = JSON.parse(fs.readFileSync(path.join(ROOT, "data/rwanda/district_production_2024.json"), "utf8"));
const MODELS = [["potato_storage", "Potato cold storage", "potato_t"], ["milk_cooling", "Milk cooling", null], ["maize_milling", "Maize milling", "maize_t"]];
const n = (v) => v === null || v === undefined ? "–" : Math.round(v).toLocaleString("en");
const kg = (d, k) => k && prod[d] ? Math.round(prod[d][k] * 1000 / prod[d].population) : null;
const names = Object.keys(S).sort();
const first = S[names[0]];
const release = first.release && /release ([0-9.-]+)/.test(first.release) ? first.release.match(/release ([0-9.-]+)/)[1] : "?";
const documented = (s) => s.documented_sites ?? (s.models.potato_storage ? s.models.potato_storage.documented : null);
const settlements = (s) => s.settlement_points ?? s.settlements;

let md = `# Rwanda national screening (all ${names.length} districts)\n\n` +
  `Generated by \`live/tools/national-report.cjs\` from \`data/rwanda/district_summaries.json\`. Data: Overture Maps ` +
  `release ${release}, OpenStreetMap (Overpass), WorldPop 2020, NISR 2024 district production, gathered on 10 October 2026. ` +
  `Each district was analysed exactly as the app does it (300 simulations, dry season)` +
  (first.engine ? `, with the engine of ${first.engine}` : "") + `. ` +
  `kWh/day is the sum over the district's top 10 sites (central estimate). These are screening figures: nothing has been ` +
  `field-verified.\n\n` +
  `| District | Buildings | People (WorldPop) | Documented facilities | Town and village points | Potato kg/person | Maize kg/person | ` +
  MODELS.map(m => `${m[1]}: ranked · robust · kWh/day`).join(" | ") + ` | Siting model: documented squares in its top 10% |\n` +
  `|---|---:|---:|---:|---:|---:|---:|` + MODELS.map(() => "---").join("|") + `|---|\n`;
names.forEach(d => {
  const s = S[d], sit = s.models.potato_storage && s.models.potato_storage.siting;
  md += `| ${d} | ${n(s.buildings)} | ${n(s.population)} | ${n(documented(s))} | ${n(settlements(s))} | ${n(kg(d, "potato_t"))} | ${n(kg(d, "maize_t"))} | ` +
    MODELS.map(([m]) => { const x = s.models[m]; return x && !x.error ? `${x.ranked} · ${x.robust} · ${n(x.top_kwh)}` : "–"; }).join(" | ") +
    ` | ${sit && sit.status === "ok" ? (sit.documented_cells ? `${sit.documented_in_top} of ${sit.documented_cells}` : "none documented") : "–"} |\n`;
});
const tot = (f) => names.reduce((a, d) => a + (f(S[d]) || 0), 0);
md += `| **Rwanda** | **${n(tot(s => s.buildings))}** | **${n(tot(s => s.population))}** | **${n(tot(documented))}** | **${n(tot(settlements))}** | | | ` +
  MODELS.map(([m]) => `**${tot(s => s.models[m] && s.models[m].ranked)} · ${tot(s => s.models[m] && s.models[m].robust)} · ${n(tot(s => s.models[m] && s.models[m].top_kwh))}**`).join(" | ") + ` | |\n`;

md += `\n## First site to check, by district\n\n| District | Potato cold storage | Milk cooling | Maize milling |\n|---|---|---|---|\n`;
names.forEach(d => { const s = S[d]; md += `| ${d} | ${MODELS.map(([m]) => (s.models[m] && s.models[m].top3 && s.models[m].top3[0]) || "–").join(" | ")} |\n`; });
md += `\n## Reading this table\n\n` +
  `- **Documented facilities** are the markets, cooperatives, mills, stores, collection centres and processing works found in ` +
  `OpenStreetMap and Overture places, after removing look-alikes (churches, schools, hotels, clubs, shops, toilets). Where none ` +
  `is documented, town and village centres stand in as possible collection points and are labelled "(no facility mapped)".\n` +
  `- **Ranked · robust**: sites in the top 10, and how many of them stay in the top 10 in at least 80% of 300 simulations.\n` +
  `- **kg/person** is the district's 2024 production divided by its 2022 census population (ESTIMATED; see ` +
  `\`data/rwanda/district_production_2024.csv\`). Milk uses the national figure, as no district series is published.\n` +
  `- **Siting model column**: how many squares with a documented facility the shipped model puts in the district's top 10%. ` +
  `This is in-sample (the model was trained on all 30 districts); the out-of-sample test is in [phase4r-results](phase4r-results.md).\n`;
fs.writeFileSync(path.join(ROOT, "docs/rwanda-national-screening.md"), md);
console.log("wrote docs/rwanda-national-screening.md", names.length, "districts");
